import React from "react";
import {
  AbsoluteFill, staticFile, interpolate, spring,
  useCurrentFrame, useVideoConfig, Sequence, Video, Easing
} from "remotion";

export const BROLL_DURATION = 576; // 24 seconds at 24 fps

export const ShortConcept3: React.FC = () => {
  return (
    <AbsoluteFill style={{ backgroundColor: "#030308" }}>
      <Sequence from={0} durationInFrames={BROLL_DURATION}>
        {/* The entire 24s B-roll generated by Seedance */}
        <Video 
          src={staticFile("youtube-assets/seedance-broll.mp4")} 
          style={{ width: "100%", height: "100%", objectFit: "cover" }} 
        />
        {/* The cinematic text overlay over the first 5 seconds */}
        <HeroTextOverlay />
      </Sequence>
    </AbsoluteFill>
  );
};

const HeroTextOverlay: React.FC = () => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig(); // 24 fps

  // TIMING
  const part1Start = 0;   // 0s
  const part2Start = 48;  // 2s
  const suckOutStart = 96;// 4s

  // Part 1: Typewriter effect using clip-path (right to left)
  // At frame 0, inset is 100% (hidden). By frame 24 (1s), inset is 0% (visible)
  const typewriterProgress = interpolate(frame, [part1Start, part1Start + 24], [100, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
    easing: Easing.out(Easing.ease)
  });

  // Part 2: Heavy 3D Slam into place
  const slamSpring = spring({
    frame: Math.max(0, frame - part2Start),
    fps,
    config: { damping: 14, stiffness: 85 } // heavier, more premium landing
  });
  const part2Scale = interpolate(slamSpring, [0, 1], [2.2, 1]);
  const part2RotateX = interpolate(slamSpring, [0, 1], [60, 0]);
  const part2Y = interpolate(slamSpring, [0, 1], [40, 0]);
  const part2Opacity = interpolate(frame, [part2Start, part2Start + 4], [0, 1], { 
    extrapolateLeft: "clamp", extrapolateRight: "clamp" 
  });
  
  // Transition OUT: Sucked into the lens (0:04 - 0:05)
  // Scale massively up, twist slightly, add blur, fade opacity
  const suckScale = interpolate(frame, [suckOutStart, suckOutStart + 16], [1, 25], {
    extrapolateLeft: "clamp", extrapolateRight: "clamp",
    easing: Easing.in(Easing.exp)
  });
  const suckRotateZ = interpolate(frame, [suckOutStart, suckOutStart + 16], [0, -10], {
    extrapolateLeft: "clamp", extrapolateRight: "clamp",
    easing: Easing.in(Easing.exp)
  });
  const suckOpacity = interpolate(frame, [suckOutStart + 6, suckOutStart + 16], [1, 0], {
    extrapolateLeft: "clamp", extrapolateRight: "clamp"
  });
  const suckBlur = interpolate(frame, [suckOutStart, suckOutStart + 16], [0, 50], {
    extrapolateLeft: "clamp", extrapolateRight: "clamp"
  });

  // Simulated 3D Camera Tracking (Text moves slightly to match handheld/drone movement)
  const trackScale = interpolate(frame, [0, 96], [0.96, 1.05], { extrapolateRight: "clamp" });
  const trackY = interpolate(frame, [0, 96], [15, -15], { extrapolateRight: "clamp" });
  const trackRotateX = Math.sin(frame * 0.04) * 2;
  const trackRotateY = Math.cos(frame * 0.03) * 3;

  return (
    <AbsoluteFill style={{
      justifyContent: "center",
      alignItems: "center",
      perspective: "1200px",
      pointerEvents: "none" // allow video to be clicked if needed
    }}>
      
      {/* The main text container that tracks the camera and gets sucked out */}
      <div style={{
        position: "absolute",
        display: "flex",
        flexDirection: "column",
        alignItems: "center",
        justifyContent: "center",
        width: "100%",
        height: "100%",
        transform: `scale(${suckScale * trackScale}) translateY(${trackY}px) rotateZ(${suckRotateZ}deg) rotateX(${trackRotateX}deg) rotateY(${trackRotateY}deg)`,
        opacity: suckOpacity,
        filter: `blur(${suckBlur}px)`,
        transformStyle: "preserve-3d",
        willChange: "transform",
        WebkitFontSmoothing: "antialiased",
        backfaceVisibility: "hidden",
      }}>

        {/* Readability scrim: Dark frosted glass to separate text from bright background */}
        <div style={{
          position: "absolute",
          top: "20%",
          bottom: "20%",
          left: "-20%",
          right: "-20%",
          background: "radial-gradient(ellipse at center, rgba(3, 3, 8, 0.8) 0%, rgba(3, 3, 8, 0.4) 40%, transparent 75%)",
          filter: "blur(30px)",
        }} />

        {/* Container for the two lines */}
        <div style={{
          position: "relative",
          display: "flex",
          flexDirection: "column",
          alignItems: "center",
          gap: 25,
          textAlign: "center",
          direction: "rtl",
          fontFamily: "'Tajawal', 'Cairo', 'Noto Sans Arabic', sans-serif",
          padding: "0 50px",
          transformStyle: "preserve-3d",
          WebkitFontSmoothing: "antialiased",
        }}>
        
        {/* PART 1 */}
        <div style={{
          fontSize: 60,
          fontWeight: 900,
          color: "#ffffff",
          textShadow: "0 10px 30px rgba(0,0,0,0.9), 0 0 20px rgba(0,0,0,0.6)",
          clipPath: `inset(0 0 0 ${typewriterProgress}%)`,
          lineHeight: 1.4,
        }}>
          جوجل أومني لغى حاجة اسمها{" "}
          <span style={{
            color: "#ec4899",
            textShadow: "0 0 40px rgba(236,72,153,0.9), 0 0 80px rgba(236,72,153,0.5)"
          }}>كروما</span>
          {" "}وتصوير..
        </div>

        {/* PART 2 */}
        {frame >= part2Start && (
          <div style={{
            fontSize: 55,
            fontWeight: 900,
            color: "#ffffff",
            textShadow: "0 15px 35px rgba(0,0,0,0.9), 0 0 25px rgba(0,0,0,0.7)",
            transform: `scale(${part2Scale}) translateY(${part2Y}px) rotateX(${part2RotateX}deg)`,
            transformOrigin: "top center",
            opacity: part2Opacity,
            lineHeight: 1.4,
            willChange: "transform",
            backfaceVisibility: "hidden",
          }}>
            الذكاء الاصطناعي بقى هو{" "}
            <span style={{
              color: "#22d3ee",
              textShadow: "0 0 40px rgba(34,211,238,0.9), 0 0 80px rgba(34,211,238,0.6)"
            }}>الاستوديو.</span>
          </div>
        )}

      </div>
      </div>
    </AbsoluteFill>
  );
};
