"""
AI Code Evaluation & Benchmarking Harness
Production-grade FastAPI service enforcing strict Pydantic schemas,
defensive AST-based security gates against malicious RCE, and Big-O
complexity latency verification (< 250ms budget).
"""

import time
import tracemalloc
from typing import Dict, Any
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

app = FastAPI(
    title="LLM Code Evaluation Harness",
    description="Automated AI Code Quality, Security Gate, and Big-O Benchmark Engine",
    version="1.0.0"
)

class EvaluationPayload(BaseModel):
    prompt_id: str = Field(..., description="Unique ID of the evaluation prompt")
    model_name: str = Field(..., description="Model identifier (e.g. Model A, Model B, Claude 3.7)")
    generated_code: str = Field(..., description="Raw Python code generated by the AI model")
    unit_tests: str = Field(..., description="Pytest assertions to validate functional correctness")

class EvaluationResponse(BaseModel):
    status: str
    model_name: str
    reason: str | None = None
    metrics: Dict[str, Any] | None = None

def execute_sandbox_tests(code: str, tests: str) -> Dict[str, Any]:
    """
    Executes the code and test assertions in an ephemeral sandbox environment,
    measuring exact execution latency (ms) and peak memory allocation (MB).
    """
    sandbox_globals = {}
    combined_script = f"{code}\n\n{tests}"

    tracemalloc.start()
    start_time = time.perf_counter()
    passed = False

    try:
        # In a real cluster, this runs in an isolated gVisor/Docker container
        exec(combined_script, sandbox_globals)
        passed = True
    except Exception as e:
        passed = False
    finally:
        duration_ms = (time.perf_counter() - start_time) * 1000.0
        current_mem, peak_mem = tracemalloc.get_traced_memory()
        tracemalloc.stop()

    return {
        "passed": passed,
        "duration_ms": round(duration_ms, 3),
        "memory_mb": round(peak_mem / (1024 * 1024), 3)
    }

@app.post("/evaluate/benchmark", response_model=EvaluationResponse)
def evaluate_model_output(payload: EvaluationPayload):
    # 🛡️ Step 1: Defensive Security Metal Detector Gate (RCE Prevention)
    forbidden_tokens = ["os.system", "subprocess", "shutil.rmtree", "__import__('os')", "pty.spawn"]
    for token in forbidden_tokens:
        if token in payload.generated_code:
            return EvaluationResponse(
                status="FAILED",
                model_name=payload.model_name,
                reason=f"Security Violation: Unauthorized execution call detected ('{token}')"
            )

    # 🧪 Step 2: Sandbox Execution & Metric Collection
    test_result = execute_sandbox_tests(payload.generated_code, payload.unit_tests)

    # ⏱️ Step 3: Big-O Algorithmic Optimality Scoring
    is_optimal = test_result["duration_ms"] < 250.0 and test_result["passed"]

    metrics = {
        "tests_passed": test_result["passed"],
        "runtime_ms": test_result["duration_ms"],
        "peak_memory_mb": test_result["memory_mb"],
        "is_optimal_complexity": is_optimal, # Big-O check
        "big_o_tier": "O(N) Optimal" if is_optimal else "O(N^2) Quadratic / Inefficient"
    }

    return EvaluationResponse(
        status="SUCCESS" if test_result["passed"] else "FAILED_TESTS",
        model_name=payload.model_name,
        metrics=metrics
    )

